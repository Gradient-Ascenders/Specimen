import { readFile, writeFile } from 'node:fs/promises';
import { chromium } from '@playwright/test';
import { CONTAINMENT_SIGNS } from '../src/render/environment/containment/ContainmentSignContent.ts';

// Bake with the installed title font, never an OS fallback. No runtime canvas or
// font request is needed. Run with the repository's pinned Playwright Chromium.
const font = await readFile(new URL('../node_modules/@fontsource/michroma/files/michroma-latin-400-normal.woff2', import.meta.url));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const width = 1024, rowHeight = 128, height = rowHeight * CONTAINMENT_SIGNS.length;
  const data = await page.evaluate(async ({ font, signs, width, height, rowHeight }) => {
    const face = new FontFace('Michroma', `url(data:font/woff2;base64,${font})`);
    document.fonts.add(await face.load());
    const canvas = document.createElement('canvas');
    canvas.width = width; canvas.height = height;
    const ctx = canvas.getContext('2d')!;
    // Logical 4:1 panel proportions. Raster width is doubled for angled views;
    // most authored panels are near 4:1, unlike the old 8:1 vector lettering.
    ctx.scale(2, 1);
    const text = (line: string, y: number, size: number, colour: string) => {
      ctx.font = `${size}px Michroma`;
      const scale = Math.min(1, 448 / ctx.measureText(line).width);
      ctx.save();
      ctx.translate(34, y); ctx.scale(scale, 1);
      ctx.fillStyle = colour;
      ctx.lineWidth = 0.55;
      ctx.strokeStyle = colour;
      ctx.textBaseline = 'top';
      ctx.strokeText(line, 0, 0); ctx.fillText(line, 0, 0);
      ctx.restore();
    };
    signs.forEach(([, title, subtitle, accent], row) => {
      const y = row * rowHeight;
      ctx.fillStyle = '#191e1f'; ctx.fillRect(0, y, 512, rowHeight);
      ctx.fillStyle = `rgb(${accent.slice(0, 3).join(',')})`;
      ctx.fillRect(0, y, 7, rowHeight); ctx.fillRect(19, y + 20, 3, 88);
      text(title, y + 6, 58, '#f1f1e9');
      text(subtitle, y + 83, 26, '#c6ceca');
    });
    // A 6-bit coverage palette preserves smooth antialiasing while keeping
    // each RGB run to three bytes (uint16 count + palette index).
    const background = [25, 30, 31];
    const palette = [background, ...signs.map(sign => sign[3].slice(0, 3))];
    for (const ink of [[241, 241, 233], [198, 206, 202]]) {
      for (let level = 1; level <= 64; level++) {
        palette.push(ink.map((value, channel) => Math.round(background[channel] +
          (value - background[channel]) * level / 64)));
      }
    }
    const rgba = ctx.getImageData(0, 0, width, height).data;
    const indices = new Uint8Array(width * height);
    for (let pixel = 0; pixel < indices.length; pixel++) {
      const y = Math.floor(pixel / width), row = Math.floor(y / rowHeight);
      const x = pixel % width, i = pixel * 4;
      if (x < 14 || (x >= 38 && x < 44 && y % rowHeight >= 20 && y % rowHeight < 108)) {
        indices[pixel] = row + 1;
      } else {
        const secondary = y % rowHeight >= 83;
        const level = Math.round((rgba[i] - 25) / ((secondary ? 198 : 241) - 25) * 64);
        indices[pixel] = level === 0 ? 0 : signs.length + (secondary ? 64 : 0) + level;
      }
    }
    const encoded: number[] = [];
    for (let i = 0; i < indices.length;) {
      let count = 1;
      while (count < 65535 && i + count < indices.length && indices[i] === indices[i + count]) count++;
      encoded.push(count & 255, count >> 8, indices[i]);
      i += count;
    }
    return { encoded, palette };
  }, { font: font.toString('base64'), signs: CONTAINMENT_SIGNS, width, height, rowHeight });
  const output = `// Generated by scripts/generate-signage.ts using bundled Michroma; do not edit.\nexport const SIGNAGE_CONTENT_JSON = ${JSON.stringify(JSON.stringify(CONTAINMENT_SIGNS))};\nexport const SIGNAGE_PALETTE = ${JSON.stringify(data.palette)};\nexport const SIGNAGE_WIDTH = ${width};\nexport const SIGNAGE_HEIGHT = ${height};\nexport const SIGNAGE_RLE_BASE64 = '${Buffer.from(data.encoded).toString('base64')}';\n`;
  const path = new URL('../src/render/environment/containment/signage.generated.ts', import.meta.url);
  if (process.argv.includes('--check')) {
    if (output !== await readFile(path, 'utf8')) throw new Error('Signage is stale. Run npm run generate:signage.');
  } else await writeFile(path, output);
  console.log(`Signage: ${width} × ${height}, ${data.encoded.length} encoded bytes.`);
} finally {
  await browser.close();
}
