import { readFile, writeFile } from 'node:fs/promises';

// Bake the complete three-octave field, not just lattice corners: three flow
// lookups replace nine value-noise evaluations. Domain warps stay analytic.
const size = 256, period = 16;
const f = Math.fround;
const fract = (value: number) => f(value - Math.floor(value));
function hash(x: number, y: number): number {
  let a = fract(f(x * f(0.1031)));
  let b = fract(f(y * f(0.1031)));
  let c = a;
  const dot = f(f(f(a * f(b + f(33.33))) + f(b * f(c + f(33.33)))) + f(c * f(a + f(33.33))));
  a = f(a + dot); b = f(b + dot); c = f(c + dot);
  return fract(f(f(a + b) * c));
}
const mix = (a: number, b: number, t: number) => a + (b - a) * t;
const smooth = (t: number) => t * t * (3 - 2 * t);
function noise(x: number, y: number): number {
  const cx = Math.floor(x), cy = Math.floor(y), bx = smooth(x - cx), by = smooth(y - cy);
  return mix(mix(hash(cx, cy), hash(cx + 1, cy), bx), mix(hash(cx, cy + 1), hash(cx + 1, cy + 1), bx), by);
}
function fbm(x: number, y: number): number {
  let result = noise(x, y) * 0.54;
  [x, y] = [(0.8 * x - 0.6 * y) * 2.03 + 7.1, (0.6 * x + 0.8 * y) * 2.03 - 3.8];
  result += noise(x, y) * 0.27;
  [x, y] = [(0.8 * x - 0.6 * y) * 2.07 - 2.6, (0.6 * x + 0.8 * y) * 2.07 + 11.4];
  return (result + noise(x, y) * 0.135) / 0.945;
}
const pixels = Buffer.alloc(size * size);
for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
  const px = x * period / size - period / 2, py = y * period / size - period / 2;
  // Blend only the outer two cells toward the opposite edge. At ±8, values
  // and first derivatives match; the central 12×12 cells keep the source FBM.
  const bx = smooth(Math.max(0, (Math.abs(px) - 6) / 2)) * 0.5;
  const by = smooth(Math.max(0, (Math.abs(py) - 6) / 2)) * 0.5;
  const ox = px - Math.sign(px) * period, oy = py - Math.sign(py) * period;
  const value = mix(mix(fbm(px, py), fbm(ox, py), bx), mix(fbm(px, oy), fbm(ox, oy), bx), by);
  pixels[y * size + x] = Math.round(value * 255);
}
const output = `// Generated by scripts/assets/generate-acid-noise.ts; do not edit.\nexport const ACID_NOISE_SIZE = ${size};\nexport const ACID_NOISE_PERIOD = ${period};\nexport const ACID_NOISE_BASE64 = '${pixels.toString('base64')}';\n`;
const url = new URL('../../src/render/environment/containment/acidNoise.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (output !== await readFile(url, 'utf8')) throw new Error('Acid noise is stale. Run node scripts/assets/generate-acid-noise.ts.');
} else await writeFile(url, output);
console.log(`Acid noise: ${size} × ${size}, ${pixels.length} bytes${process.argv.includes('--check') ? ' reproduced exactly' : ''}.`);
